
"""
SCRIPT 104
Statistical Evaluation of Automatic Lung Constraints

Compares:
1. Unconstrained infection segmentation
2. Infection segmentation constrained by predicted lung masks

Uses the per-image results generated by Script 102.
No model training is performed.
"""

from pathlib import Path
import json
import warnings

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon


# ============================================================
# CONFIGURATION
# ============================================================

ROOT = Path(__file__).resolve().parents[1]

INPUT_CSV = (
    ROOT
    / "results"
    / "infection_segmentation"
    / "automatic_lung_constraint_analysis"
    / "automatic_lung_constraint_per_image.csv"
)

OUTPUT_DIR = (
    ROOT
    / "results"
    / "infection_segmentation"
    / "automatic_constraint_statistical_evaluation"
)

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

RANDOM_SEED = 42
BOOTSTRAP_ITERATIONS = 5000
DICE_EQUALITY_TOLERANCE = 1e-6


# ============================================================
# COLUMN DETECTION
# ============================================================

