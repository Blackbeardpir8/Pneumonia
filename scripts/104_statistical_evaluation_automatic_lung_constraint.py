def find_column(df, logical_name, required=False):
    """Find a column using a list of accepted names."""

    for candidate in COLUMN_ALIASES.get(logical_name, []):
        if candidate in df.columns:
            return candidate

    if required:
        raise ValueError(
            f"Required column '{logical_name}' was not found.\n"
            f"Accepted names: {COLUMN_ALIASES.get(logical_name)}\n"
            f"Available columns: {list(df.columns)}"
        )

    return None


# ============================================================
# BOOTSTRAP CONFIDENCE INTERVAL
# ============================================================

def bootstrap_mean_ci(values, iterations=BOOTSTRAP_ITERATIONS):
    """Calculate a percentile 95% bootstrap CI for the mean."""

    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]

    if len(values) == 0:
        return None, None

    rng = np.random.default_rng(RANDOM_SEED)

    bootstrap_means = np.empty(iterations)

    for i in range(iterations):
        sample = rng.choice(
            values,
            size=len(values),
            replace=True,
        )
        bootstrap_means[i] = np.mean(sample)

    lower, upper = np.percentile(
        bootstrap_means,
        [2.5, 97.5],
    )

    return float(lower), float(upper)


# ============================================================
# DESCRIPTIVE STATISTICS
# ============================================================

def calculate_dice_statistics(df, group_name):
    """Calculate statistics for paired Dice differences."""

    delta = (
        df["constrained_dice"]
        - df["unconstrained_dice"]
    ).to_numpy(dtype=float)

    delta = delta[np.isfinite(delta)]

    improved = np.sum(delta > DICE_EQUALITY_TOLERANCE)
    worsened = np.sum(delta < -DICE_EQUALITY_TOLERANCE)
    unchanged = len(delta) - improved - worsened

    ci_low, ci_high = bootstrap_mean_ci(delta)

    return {
        "group": str(group_name),
        "image_count": int(len(delta)),
        "unconstrained_mean_dice": float(
            df["unconstrained_dice"].mean()
        ),
        "constrained_mean_dice": float(
            df["constrained_dice"].mean()
        ),
        "mean_dice_change": float(np.mean(delta)),
        "median_dice_change": float(np.median(delta)),
        "dice_change_std": float(np.std(delta, ddof=1))
        if len(delta) > 1 else 0.0,
        "dice_change_95ci_lower": ci_low,
        "dice_change_95ci_upper": ci_high,
        "improved_images": int(improved),
        "worsened_images": int(worsened),
        "unchanged_images": int(unchanged),
        "improved_percentage": float(improved / len(delta) * 100),
        "worsened_percentage": float(worsened / len(delta) * 100),
        "unchanged_percentage": float(unchanged / len(delta) * 100),
    }


# ============================================================
# PAIRED WILCOXON TEST
# ============================================================

def paired_wilcoxon(df):
    """Test paired Dice scores."""

    before = df["unconstrained_dice"].to_numpy(dtype=float)
    after = df["constrained_dice"].to_numpy(dtype=float)

    difference = after - before

    if np.all(np.abs(difference) <= DICE_EQUALITY_TOLERANCE):
        return {
            "test": "Wilcoxon signed-rank test",
            "statistic": 0.0,
            "p_value": 1.0,
            "interpretation": "No measurable paired Dice differences.",
        }

    try:
        statistic, p_value = wilcoxon(
            before,
            after,
            alternative="two-sided",
            zero_method="wilcox",
        )

        return {
            "test": "Wilcoxon signed-rank test",
            "statistic": float(statistic),
            "p_value": float(p_value),
            "interpretation": (
                "Statistically significant paired difference."
                if p_value < 0.05
                else "No statistically significant paired difference."
            ),
        }

    except Exception as exc:
        return {
            "test": "Wilcoxon signed-rank test",
            "error": str(exc),
        }


# ============================================================
# LOAD AND PREPARE DATA
# ============================================================

def main():

    print("=" * 80)
    print("STATISTICAL EVALUATION OF AUTOMATIC LUNG CONSTRAINTS")
    print("=" * 80)

    if not INPUT_CSV.exists():
        raise FileNotFoundError(
            f"Script 102 CSV not found:\n{INPUT_CSV}"
        )

    raw_df = pd.read_csv(INPUT_CSV)

    print(f"\nInput records: {len(raw_df)}")
    print("\nAvailable input columns:")
    for column in raw_df.columns:
        print(f"  - {column}")

    unconstrained_col = find_column(
        raw_df, "unconstrained_dice", required=True
    )

    constrained_col = find_column(
        raw_df, "constrained_dice", required=True
    )

    image_col = find_column(raw_df, "image_name")
    group_col = find_column(raw_df, "annotation_group")
    area_ratio_col = find_column(raw_df, "infection_area_ratio")

    fp_before_col = find_column(raw_df, "unconstrained_fp")
    fp_after_col = find_column(raw_df, "constrained_fp")

    tp_before_col = find_column(raw_df, "unconstrained_tp")
    tp_after_col = find_column(raw_df, "constrained_tp")

    fn_before_col = find_column(raw_df, "unconstrained_fn")
    fn_after_col = find_column(raw_df, "constrained_fn")

    df = pd.DataFrame()

    df["image_name"] = (
        raw_df[image_col].astype(str)
        if image_col
        else [f"image_{i + 1}" for i in range(len(raw_df))]
    )

    df["unconstrained_dice"] = pd.to_numeric(
        raw_df[unconstrained_col],
        errors="coerce",
    )

    df["constrained_dice"] = pd.to_numeric(
        raw_df[constrained_col],
        errors="coerce",
    )

    if group_col:
        df["annotation_group"] = raw_df[group_col].astype(str)

    elif area_ratio_col:
        ratio = pd.to_numeric(
            raw_df[area_ratio_col],
            errors="coerce",
        )

        # These are annotation-area groups, NOT clinical severity.
        df["annotation_group"] = pd.cut(
            ratio,
            bins=[-np.inf, 0.01, 0.10, 0.50, 0.90, np.inf],
            labels=[
                "VERY_SMALL",
                "SMALL",
                "MODERATE",
                "LARGE",
                "VERY_LARGE",
            ],
        ).astype(str)

    else:
        df["annotation_group"] = "ALL_IMAGES"

    optional_columns = {
        "unconstrained_fp": fp_before_col,
        "constrained_fp": fp_after_col,
        "unconstrained_tp": tp_before_col,
        "constrained_tp": tp_after_col,
        "unconstrained_fn": fn_before_col,
        "constrained_fn": fn_after_col,
    }

    for output_name, source_name in optional_columns.items():
        if source_name:
            df[output_name] = pd.to_numeric(
                raw_df[source_name],
                errors="coerce",
            )

    initial_count = len(df)

    df = df.dropna(
        subset=["unconstrained_dice", "constrained_dice"]
    ).copy()

    df = df[
        df["unconstrained_dice"].between(0, 1)
        & df["constrained_dice"].between(0, 1)
    ].copy()

    print(f"\nValid paired records: {len(df)}")
    print(f"Excluded invalid records: {initial_count - len(df)}")

    if len(df) < 2:
        raise ValueError(
            "Not enough valid paired records for statistical analysis."
        )

    df["dice_change"] = (
        df["constrained_dice"]
        - df["unconstrained_dice"]
    )

    df["result"] = np.select(
        [
            df["dice_change"] > DICE_EQUALITY_TOLERANCE,
            df["dice_change"] < -DICE_EQUALITY_TOLERANCE,
        ],
        [
            "IMPROVED",
            "WORSENED",
        ],
        default="UNCHANGED",
    )

    # Save per-image comparison.
    per_image_path = OUTPUT_DIR / "per_image_dice_comparison.csv"
    df.to_csv(per_image_path, index=False)

    # ========================================================
    # OVERALL ANALYSIS
    # ========================================================

    overall = calculate_dice_statistics(df, "ALL_IMAGES")
    wilcoxon_result = paired_wilcoxon(df)

    print("\n" + "=" * 80)
    print("OVERALL DICE COMPARISON")
    print("=" * 80)

    print(
        f"Unconstrained mean Dice: "
        f"{overall['unconstrained_mean_dice']:.6f}"
    )
    print(
        f"Automatic constrained mean Dice: "
        f"{overall['constrained_mean_dice']:.6f}"
    )
    print(
        f"Mean Dice change: "
        f"{overall['mean_dice_change']:+.6f}"
    )
    print(
        f"Median Dice change: "
        f"{overall['median_dice_change']:+.6f}"
    )

    print(
        f"95% bootstrap CI: "
        f"[{overall['dice_change_95ci_lower']:.6f}, "
        f"{overall['dice_change_95ci_upper']:.6f}]"
    )

    print(f"\nImproved: {overall['improved_images']}")
    print(f"Worsened: {overall['worsened_images']}")
    print(f"Unchanged: {overall['unchanged_images']}")

    print("\nPaired Wilcoxon test:")
    print(wilcoxon_result)

    # ========================================================
    # PIXEL-LEVEL ERROR COMPARISON
    # ========================================================

    pixel_summary = {}

    if fp_before_col and fp_after_col:
        fp_before = df["unconstrained_fp"]
        fp_after = df["constrained_fp"]

        pixel_summary["false_positives"] = {
            "unconstrained_total": int(fp_before.sum()),
            "constrained_total": int(fp_after.sum()),
            "pixels_removed": int((fp_before - fp_after).sum()),
            "mean_removed_per_image": float(
                (fp_before - fp_after).mean()
            ),
        }

    if tp_before_col and tp_after_col:
        tp_before = df["unconstrained_tp"]
        tp_after = df["constrained_tp"]

        pixel_summary["true_positives"] = {
            "unconstrained_total": int(tp_before.sum()),
            "constrained_total": int(tp_after.sum()),
            "pixels_gained_or_lost": int(
                (tp_after - tp_before).sum()
            ),
            "mean_change_per_image": float(
                (tp_after - tp_before).mean()
            ),
        }

    if fn_before_col and fn_after_col:
        fn_before = df["unconstrained_fn"]
        fn_after = df["constrained_fn"]

        pixel_summary["false_negatives"] = {
            "unconstrained_total": int(fn_before.sum()),
            "constrained_total": int(fn_after.sum()),
            "additional_or_removed_fn": int(
                (fn_after - fn_before).sum()
            ),
            "mean_change_per_image": float(
                (fn_after - fn_before).mean()
            ),
        }

    print("\n" + "=" * 80)
    print("PIXEL-LEVEL COMPARISON")
    print("=" * 80)

    if pixel_summary:
        print(json.dumps(pixel_summary, indent=4))
    else:
        print(
            "Pixel-level TP/FP/FN columns were not available. "
            "Only Dice analysis will be reported."
        )

    # ========================================================
    # ANNOTATION-GROUP ANALYSIS
    # ========================================================

    group_rows = []

    print("\n" + "=" * 80)
    print("ANNOTATION-GROUP ANALYSIS")
    print("=" * 80)

    for group_name, group_df in df.groupby(
        "annotation_group",
        observed=True,
    ):

        if len(group_df) < 2:
            print(
                f"\n{group_name}: skipped "
                f"(fewer than two images)"
            )
            continue

        result = calculate_dice_statistics(
            group_df,
            group_name,
        )

        group_rows.append(result)

        print(f"\n{group_name}")
        print(f"  Images: {result['image_count']}")
        print(
            f"  Unconstrained Dice: "
            f"{result['unconstrained_mean_dice']:.6f}"
        )
        print(
            f"  Constrained Dice: "
            f"{result['constrained_mean_dice']:.6f}"
        )
        print(
            f"  Mean change: "
            f"{result['mean_dice_change']:+.6f}"
        )
        print(
            f"  Improved / Worsened / Unchanged: "
            f"{result['improved_images']} / "
            f"{result['worsened_images']} / "
            f"{result['unchanged_images']}"
        )

    group_df = pd.DataFrame(group_rows)

    if not group_df.empty:
        group_df.to_csv(
            OUTPUT_DIR / "annotation_group_comparison.csv",
            index=False,
        )

    # ========================================================
    # SAVE SUMMARY
    # ========================================================

    summary = {
        "study": "Automatic lung constraint statistical evaluation",
        "input_file": str(INPUT_CSV),
        "valid_image_count": int(len(df)),
        "overall_dice_statistics": overall,
        "paired_wilcoxon_test": wilcoxon_result,
        "pixel_level_comparison": pixel_summary,
        "annotation_group_statistics": group_rows,
        "limitations": [
            "This is a validation-set experiment, not clinical validation.",
            "Reference infection masks are used as evaluation targets.",
            "Predicted lung masks may exclude valid infection pixels.",
            "Annotation groups describe mask geometry, not clinical severity.",
            "Statistical significance does not establish clinical importance.",
        ],
    }

    summary_path = OUTPUT_DIR / "statistical_evaluation_summary.json"

    with open(summary_path, "w", encoding="utf-8") as file:
        json.dump(summary, file, indent=4, allow_nan=False)

    print("\n" + "=" * 80)
    print("SCRIPT 104 COMPLETED")
    print("=" * 80)

    print(f"\nOutput directory:\n{OUTPUT_DIR}")

    print("\nGenerated files:")
    print("1. per_image_dice_comparison.csv")
    print("2. annotation_group_comparison.csv (if groups are available)")
    print("3. statistical_evaluation_summary.json")

    print("\nImportant:")
    print(
        "Annotation-area groups are geometric categories, "
        "not clinical severity stages."
    )


if __name__ == "__main__":
    main()

